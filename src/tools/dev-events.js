// V-3 native curated TEST event actions; no fictional synthetic event responses.
import {defineWrite,gone} from './write.js';
import {client,reply,writeProfiles,allProfiles} from './billing-shared.js';
import {planTrigger,executeTrigger,triggerTypes,verifyRecordedTriggerRun} from '../dev/triggers.js';
import {pendingTriggerReceipt} from '../dev/trigger-pending-receipt.js';
import {verifyCheckoutSession,verifiedHostedCheckoutUrl}
  from '../dev/triggers-checkout.js';
const types=triggerTypes.map(type=>({
  type,requires:'Guarded TEST API action and independently observed Stripe event',
  asyncMayLag:true
}));
const op=defineWrite({
  name:'dev_trigger_event',allowZeroPreview:true,
  // Only an independently event-verified and audited completed run exposes its ID.
  resultId:(_before,after)=>after?.id,
  read:async(a,ctx)=>{
    if(ctx?.connection?.mode!=='test')throw new TypeError('TEST event trigger only');
    if(!ctx.db||typeof ctx.db.ensureDevRun!=='function'||
      typeof ctx.db.getDevRunObjects!=='function'||
      typeof ctx.db.recordDevRunObject!=='function')
      throw new TypeError('Durable TEST event run ledger unavailable');
    const plan=planTrigger(a,ctx.connection.stripeAccount);
    const prior=await ctx.db.getDevRun({
      account:ctx.connection.stripeAccount,requestKey:a.requestKey});
    if(prior&&(prior.id!==plan.runId||prior.scenario!==plan.scenario||
      prior.size!==plan.size||prior.plan_digest!==plan.planDigest))
      throw new TypeError('Immutable TEST event plan conflicts with prior run');
    return {id:plan.runId,metadata:{},...plan,_prior:prior};
  },
  summarize:p=>'TEST MODE. Make Stripe emit '+p.type+' from '+
    p.steps.filter(s=>s.type!=='event').map(s=>s.type).join(', ')+
    '. Record run '+p.runId+' and verify exact source IDs, metadata and event. '+
    'Stripe event listing can lag; retry same requestKey without recreating '+
    'objects. Unobserved event is UNKNOWN, not completed. No LIVE or money out.',
  money:async(_a,_ctx,b)=>b.amountCents?{
    amountCents:b.amountCents,currency:'usd',direction:'in',targetId:b.runId,
    description:'Synthetic incoming TEST card for event trigger'}:null,
  targetGuard:(_a,_ctx,b)=>b._prior?.status==='uncertain'?
    'Event run has uncertain result and cannot safely resume':true,
  apply:async(a,ctx,{before,idempotencyKey})=>{
    const account=ctx.connection.stripeAccount;
    const run=await ctx.db.ensureDevRun({
      id:before.runId,account,requestKey:a.requestKey,
      scenario:before.scenario,size:1,planDigest:before.planDigest,
      connection:ctx.connectionId??null});
    await executeTrigger({plan:before,run,stripe:await client(ctx),
      db:ctx.db,account,rootKey:idempotencyKey});
  },
  readAfter:async(a,ctx)=>{
    const account=ctx.connection.stripeAccount;
    const run=await ctx.db.getDevRun({account,requestKey:a.requestKey});
    if(!run)return null;
    return {...run,objects:await ctx.db.getDevRunObjects({account,id:run.id})};
  },
  verify:(plan,after)=>after?.id===plan.runId&&
    after?.plan_digest===plan.planDigest&&after.status==='completed'&&
    Array.isArray(after.objects)&&after.objects.length===plan.expectedSteps&&
    plan.steps.every(step=>after.objects.some(row=>
      row.step_name===step.name&&row.object_type===step.type&&
      row.cleaned===false))
});
